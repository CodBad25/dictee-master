const exportPath = path.join(__dirname, "dictee-words-export.json");
const data = JSON.parse(fs.readFileSync(exportPath, "utf8"));

const sqlLines = [
  "-- Bootstrap spelling_errors — généré le " + new Date().toISOString(),
  "-- Dictée 13 EXCLUE volontairement (déjà enrichie à la main).",
  "-- Règles : pas d'accord (nombre/genre), pas de conjugaison sur infinitif,",
  "-- un distracteur ≠ autre mot existant, 1 distracteur fort > 2 dont 1 faible.",
  "-- À appliquer dans Supabase SQL editor.",
  "",
  "BEGIN;",
  "",
];

let total = 0;
let withErrors = 0;
let skipped = 0;

for (const dictee of data) {
  if (dictee.position === 13) continue;
  const decisions = DECISIONS[dictee.position];
  if (!decisions) {
    skipped += dictee.words.length;
    continue;
  }
  sqlLines.push(`-- Dictée ${dictee.position}`);
  for (const word of dictee.words) {
    total++;
    const errors = decisions[word.position];
    if (!errors || errors.length === 0) continue;
    withErrors++;
    const escaped = errors.map((e) => `'${e.replace(/'/g, "''")}'`).join(",");
    const safeLabel = word.word.replace(/'/g, "''").replace(/\n/g, " ");
    sqlLines.push(
      `UPDATE dictee_words SET spelling_errors = ARRAY[${escaped}]::text[] WHERE id = '${word.id}'; -- "${safeLabel}"`,
    );
  }
  sqlLines.push("");
}

sqlLines.push("COMMIT;");
sqlLines.push("");
sqlLines.push(`-- Stats : ${withErrors} mots enrichis / ${total} traités / ${skipped} non traités.`);

process.stdout.write(sqlLines.join("\n"));
